"""Generate src/par/par_graph.h: one decoding graph wired into the parallel decoder.

Usage: python python/gen_par_graph.py <case_dir>/graph.txt [--out src/par/par_graph.h]

The parallel prototype (src/par/par_decoder.cpp) has one processing element per node and
per edge, like Helios and Collision Clustering, so the graph's topology is fixed at
synthesis time. This script writes the topology and weights as constants plus
straight-line functions (every node's neighbours spelled out), so HLS builds plain
wires and comparators instead of lookup tables.

Generated functions (all inlined, constant indices only):
  flood(lab, grown, nl)        nl[v] = min(lab[v], lab[u] over grown edges (v, u))
  edge_rate(lab, actn, grown, rate)
  grow_step(rate, sup)         smallest growth step that fully grows a rated edge
  bfs_level(...)               one level of the peeling forest: parent = smallest-ID
                               reached neighbour on the level above, then smallest edge ID
  pass_up(...)                 residual parities passed one level up the forest
  cluster_up / cluster_down    cluster parity up a forest rooted at each label, then
                               "active" back down (no N^2 crossbar)
"""

import argparse
import os


def tree(terms, op):
    """Balanced expression tree over terms with binary function op(a, b) -> str."""
    if not terms:
        return None
    while len(terms) > 1:
        nxt = [op(terms[i], terms[i + 1]) for i in range(0, len(terms) - 1, 2)]
        if len(terms) % 2:
            nxt.append(terms[-1])
        terms = nxt
    return terms[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("graph")
    ap.add_argument("--out", default="src/par/par_graph.h")
    ap.add_argument("--split-boundary", type=int, default=8,
                    help="boundary edges per virtual boundary node (keeps every node's fan-in small)")
    args = ap.parse_args()

    edges = []
    header = None
    for line in open(args.graph):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if header is None:
            header = [int(x) for x in line.split()]
            continue
        u, v, w, obs = (int(x) for x in line.split())
        edges.append((u, v, w, obs))
    num_det, num_obs, num_edges = header
    assert len(edges) == num_edges and num_obs == 1
    # The boundary is split into G virtual nodes with the smallest IDs (0..G-1), K
    # boundary edges each in edge order; detector i is node G + i. A cluster touching the
    # boundary then has a virtual node as its label (smallest ID), and no node has a
    # large fan-in. tools/par_model.cpp --split-boundary K builds the same forest.
    K = args.split_boundary
    nbe = sum(1 for (u, v, w, o) in edges if v < 0)
    G = (nbe + K - 1) // K
    B = G
    N = G + num_det
    out_edges, j = [], 0
    for (u, v, w, o) in edges:
        if v < 0:
            out_edges.append((G + u, j // K, w, o))
            j += 1
        else:
            out_edges.append((G + u, G + v, w, o))
    edges = out_edges

    inc = [[] for _ in range(N)]          # (neighbour, edge) per node
    for e, (u, v, w, o) in enumerate(edges):
        inc[u].append((v, e))
        inc[v].append((u, e))
    for lst in inc:
        lst.sort()

    L = []
    w = L.append
    w("// Generated by python/gen_par_graph.py from " + os.path.relpath(args.graph) + ". Do not edit.")
    w("#ifndef PAR_GRAPH_H")
    w("#define PAR_GRAPH_H")
    w("#include <cstdint>")
    w("namespace par {")
    w(f"constexpr int PG = {G};          // virtual boundary nodes 0..PG-1 ({K} boundary edges each)")
    w(f"constexpr int PDET = {num_det};  // detectors: detector i is node PG + i")
    w(f"constexpr int PN = {N};          // nodes")
    w(f"constexpr int PE = {num_edges};  // edges")
    w(f"constexpr int PDW = {(num_det + 31) // 32};  // 32-bit words per shot")
    w(f"constexpr int PMAXDEG = {max(len(x) for x in inc)};")
    w("typedef uint8_t lab_t;" if N <= 255 else "typedef uint16_t lab_t;")
    w(f"constexpr lab_t PMAXL = {255 if N <= 255 else 65535};")
    w("constexpr int PEU[PE] = {" + ", ".join(str(e[0]) for e in edges) + "};")
    w("constexpr int PEV[PE] = {" + ", ".join(str(e[1]) for e in edges) + "};")
    w("constexpr uint8_t PW2[PE] = {" + ", ".join(str(2 * e[2]) for e in edges) + "};")
    w("constexpr uint8_t POBS[PE] = {" + ", ".join(str(e[3]) for e in edges) + "};")

    # flood: balanced min tree per node
    w("inline lab_t min2(lab_t a, lab_t b) {")
    w("#pragma HLS INLINE")
    w("    return a < b ? a : b;")
    w("}")
    w("inline void flood(const lab_t lab[PN], const bool grown[PE], lab_t nl[PN]) {")
    w("#pragma HLS INLINE")
    for v in range(N):
        terms = [f"lab[{v}]"] + [f"(grown[{e}] ? lab[{u}] : PMAXL)" for (u, e) in inc[v]]
        w(f"    nl[{v}] = " + tree(terms, lambda a, b: f"min2({a}, {b})") + ";")
    w("}")

    # edge rate
    w("inline void edge_rate(const lab_t lab[PN], const bool actn[PN], const bool grown[PE], uint8_t rate[PE]) {")
    w("#pragma HLS INLINE")
    for e, (u, v, _, _) in enumerate(edges):
        w(f"    rate[{e}] = (!grown[{e}] && lab[{u}] != lab[{v}]) ? (uint8_t)(actn[{u}] + actn[{v}]) : (uint8_t)0;")
    w("}")

    # smallest step that fully grows some rated edge: balanced min tree over edges
    w("inline uint8_t min8(uint8_t a, uint8_t b) {")
    w("#pragma HLS INLINE")
    w("    return a < b ? a : b;")
    w("}")
    w("inline uint8_t grow_step(const uint8_t rate[PE], const uint8_t sup[PE]) {")
    w("#pragma HLS INLINE")
    w("    uint8_t s[PE];")
    w("#pragma HLS ARRAY_PARTITION variable=s complete")
    w("    for (int e = 0; e < PE; ++e) {")
    w("#pragma HLS UNROLL")
    w("        const uint8_t rem = PW2[e] - sup[e];")
    w("        s[e] = rate[e] == 0 ? (uint8_t)255 : rate[e] == 2 ? (uint8_t)((rem + 1) >> 1) : rem;")
    w("    }")
    w("    return " + tree([f"s[{e}]" for e in range(num_edges)], lambda a, b: f"min8({a}, {b})") + ";")
    w("}")

    # the same minimum as a pipeline over several clock cycles: stage 0 computes each
    # edge's remaining step into a register, every later stage takes minima of groups
    # of 8 registers from the stage before (three comparator levels per cycle)
    sizes = [num_edges]
    while sizes[-1] > 1:
        sizes.append((sizes[-1] + 7) // 8)
    offs = [0]
    for z in sizes[:-1]:
        offs.append(offs[-1] + z)
    w(f"constexpr int PPM = {sum(sizes)};      // registers of the step-minimum pipeline")
    w(f"constexpr int PSTAGES = {len(sizes)};  // its clock cycles; the minimum is pm[PPM - 1]")
    w("inline void step_stage(uint8_t k, const uint8_t rate[PE], const uint8_t sup[PE], uint8_t pm[PPM]) {")
    w("#pragma HLS INLINE")
    w("    if (k == 0) {")
    w("        for (int e = 0; e < PE; ++e) {")
    w("#pragma HLS UNROLL")
    w("            const uint8_t rem = PW2[e] - sup[e];")
    w("            pm[e] = rate[e] == 0 ? (uint8_t)255 : rate[e] == 2 ? (uint8_t)((rem + 1) >> 1) : rem;")
    w("        }")
    w("    }")
    for k in range(1, len(sizes)):
        w(f"    if (k == {k}) {{")
        for j in range(sizes[k]):
            src = [f"pm[{offs[k - 1] + i}]" for i in range(8 * j, min(sizes[k - 1], 8 * j + 8))]
            w(f"        pm[{offs[k] + j}] = " + tree(src, lambda a, b: f"min8({a}, {b})") + ";")
        w("    }")
    w("}")

    # The forest: lv[v] is the node's level (roots 0), and the parent edge is kept as
    # one bit per edge end: pu[e] says "edge e is the parent edge of its end u",
    # pv[e] the same for end v. A node writes all its bits when it joins, and roots
    # are never read as children (every pass below works on levels >= 1), so old bits
    # need no reset. Each node compares its level once per cycle (atl), not once per
    # edge.
    def side(v, e):
        return "pu" if edges[e][0] == v else "pv"
    w("typedef " + ("uint8_t" if N <= 255 else "uint16_t") + " lvl_t;")
    w("inline void at_level(const lvl_t lv[PN], lvl_t lvl, bool atl[PN]) {")
    w("#pragma HLS INLINE")
    w("    for (int v = 0; v < PN; ++v) {")
    w("#pragma HLS UNROLL")
    w("        atl[v] = lv[v] == lvl;")
    w("    }")
    w("}")
    # one BFS level: nodes not reached, with a reached neighbour on level `lvl` over a
    # grown edge, join level lvl+1; parent = first match in (neighbour, edge) order.
    w("inline bool bfs_level(const bool grown[PE], bool reached[PN], lvl_t lv[PN], bool pu[PE], bool pv[PE], lvl_t lvl) {")
    w("#pragma HLS INLINE")
    w("    bool atl[PN];")
    w("#pragma HLS ARRAY_PARTITION variable=atl complete")
    w("    at_level(lv, lvl, atl);")
    w("    bool rch[PN];   // reached before this level: every node decides from the same state")
    w("#pragma HLS ARRAY_PARTITION variable=rch complete")
    w("    for (int v = 0; v < PN; ++v) {")
    w("#pragma HLS UNROLL")
    w("        rch[v] = reached[v];")
    w("    }")
    w("    bool any = false;")
    for v in range(N):
        if not inc[v]:
            continue
        w("    {")
        for k, (u, e) in enumerate(inc[v]):
            w(f"        const bool c{k} = grown[{e}] && rch[{u}] && atl[{u}];")
        w("        const bool j = !rch[" + str(v) + "] && (" + " || ".join(f"c{k}" for k in range(len(inc[v]))) + ");")
        w("        if (j) {")
        w(f"            reached[{v}] = true;")
        w(f"            lv[{v}] = lvl + 1;")
        for k, (u, e) in enumerate(inc[v]):
            first = " && ".join([f"c{k}"] + [f"!c{i}" for i in range(k)])
            w(f"            {side(v, e)}[{e}] = {first};")
        w("            any = true;")
        w("        }")
        w("    }")
    w("    return any;")
    w("}")

    def up_terms(arr):
        out = []
        for e, (u, v, _, _) in enumerate(edges):
            out.append(f"    up[{e}] = (pu[{e}] && atl[{u}] && {arr}[{u}]) || (pv[{e}] && atl[{v}] && {arr}[{v}]);")
        return out
    # pass residuals one level up: children on level lvl with residual flip their
    # parent (balanced XOR trees)
    w("inline uint32_t pass_up(const bool pu[PE], const bool pv[PE], const lvl_t lv[PN], bool res[PN], lvl_t lvl) {")
    w("#pragma HLS INLINE")
    w("    bool atl[PN];")
    w("#pragma HLS ARRAY_PARTITION variable=atl complete")
    w("    at_level(lv, lvl, atl);")
    w("    bool up[PE];")
    w("#pragma HLS ARRAY_PARTITION variable=up complete")
    for x in up_terms("res"):
        w(x)
    w("    bool flip[PN];")
    w("#pragma HLS ARRAY_PARTITION variable=flip complete")
    for v in range(N):
        terms = [f"up[{e}]" for (u, e) in inc[v]]
        w(f"    flip[{v}] = " + (tree(terms, lambda a, b: f"({a} ^ {b})") if terms else "false") + ";")
    oterms = [f"up[{e}]" for e, ed in enumerate(edges) if ed[3]]
    w("    const bool o = " + (tree(oterms, lambda a, b: f"({a} ^ {b})") if oterms else "false") + ";")
    w("    for (int v = 0; v < PN; ++v) {")
    w("#pragma HLS UNROLL")
    w("        if (atl[v]) res[v] = false;   // lvl >= 1: a child, its residual went up")
    w("        if (flip[v] && v >= PG) res[v] = !res[v];   // virtual boundary nodes absorb")
    w("    }")
    w("    return o ? 1u : 0u;")
    w("}")
    # cluster parity without an all-pairs crossbar: on a forest rooted at each label,
    # parity (XOR) is passed up one level per call, then "active" back down one level
    # per call. Only neighbour wiring. (A cluster touches the boundary exactly when its
    # label is a virtual boundary node, label < PG.)
    w("inline void cluster_up(const bool pu[PE], const bool pv[PE], const lvl_t lv[PN], bool par[PN], lvl_t lvl) {")
    w("#pragma HLS INLINE")
    w("    bool atl[PN];")
    w("#pragma HLS ARRAY_PARTITION variable=atl complete")
    w("    at_level(lv, lvl, atl);")
    w("    bool up[PE];")
    w("#pragma HLS ARRAY_PARTITION variable=up complete")
    for x in up_terms("par"):
        w(x)
    for v in range(N):
        tx = [f"up[{e}]" for (u, e) in inc[v]]
        if not tx:
            continue
        w(f"    if (!atl[{v}]) par[{v}] = par[{v}] ^ " + tree(tx, lambda a, b: f"({a} ^ {b})") + ";")
    w("}")
    w("inline void cluster_down(const bool pu[PE], const bool pv[PE], const lvl_t lv[PN], bool act[PN], lvl_t lvl) {")
    w("#pragma HLS INLINE")
    w("    bool atl[PN];")
    w("#pragma HLS ARRAY_PARTITION variable=atl complete")
    w("    at_level(lv, (lvl_t)(lvl + 1), atl);")
    w("    bool nx[PN];")
    w("#pragma HLS ARRAY_PARTITION variable=nx complete")
    for v in range(N):
        terms = [f"({side(v, e)}[{e}] && act[{u}])" for (u, e) in inc[v]]
        rhs = tree(terms, lambda a, b: f"({a} || {b})") if terms else "false"
        w(f"    nx[{v}] = atl[{v}] ? {rhs} : act[{v}];")
    w("    for (int v = 0; v < PN; ++v) {")
    w("#pragma HLS UNROLL")
    w("        act[v] = nx[v];")
    w("    }")
    w("}")
    w("}  // namespace par")
    w("#endif")

    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {args.out}: {N} nodes ({G} virtual boundary), {num_edges} edges, max degree {max(len(x) for x in inc)}")


if __name__ == "__main__":
    main()
